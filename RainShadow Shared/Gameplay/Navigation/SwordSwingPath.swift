    static func blade(phase: Double, facing: ActorFacing, maneuver: CombatManeuver? = nil) -> (base: CGPoint, tip: CGPoint) {
        let poses = maneuver == .tripAttack ? tripPoses : maneuver == .powerStrike ? powerPoses : maneuver == .feintingCut ? feintPoses : Self.poses
        let last = poses.count - 1
        let phase = min(Double(last), max(0, phase)), i = Int(phase), t = phase - Double(i)
        func value(_ component: Int) -> Double {
            let a = poses[max(0, i - 1)][component], b = poses[i][component]
            let c = poses[min(last, i + 1)][component], d = poses[min(last, i + 2)][component]
            return 0.5 * ((2 * b) + (-a + c) * t + (2*a - 5*b + 4*c - d) * t*t
                          + (-a + 3*b - 3*c + d) * t*t*t)
        }
        let angle = Double(facing.rawValue) * .pi / 8
        let density = (1024 / 1.72 * 0.07465790639916813) * (140.625 / 128)
        func project(_ offset: Int) -> CGPoint {
            let x = value(offset), y = value(offset + 1), z = value(offset + 2)
            return CGPoint(x: density * (cos(angle)*x + sin(angle)*y),
                y: density * (sqrt(1 - 0.75*0.75)*z - 0.75*(sin(angle)*x - cos(angle)*y)))
        }
        return (project(0), project(3))
    }
